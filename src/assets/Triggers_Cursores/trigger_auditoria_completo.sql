CREATE TABLE log_cambios_empleados (
    id_log      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    usuario     VARCHAR2(50),
    fecha       TIMESTAMP,
    accion      VARCHAR2(20),
    emp_id      NUMBER
);

CREATE OR REPLACE TRIGGER trg_audit_empleados
AFTER INSERT OR UPDATE OR DELETE ON employees
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO log_cambios_empleados (usuario, fecha, accion, emp_id)
        VALUES (USER, SYSTIMESTAMP, 'INSERT', :NEW.employee_id);
    ELSIF UPDATING THEN
        INSERT INTO log_cambios_empleados (usuario, fecha, accion, emp_id)
        VALUES (USER, SYSTIMESTAMP, 'UPDATE', :NEW.employee_id);
    ELSIF DELETING THEN
        INSERT INTO log_cambios_empleados (usuario, fecha, accion, emp_id)
        VALUES (USER, SYSTIMESTAMP, 'DELETE', :OLD.employee_id);
    END IF;
END;
